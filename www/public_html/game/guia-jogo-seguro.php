            <h2>1. Introdução: Jogar é Legal, Jogar Seguro é Essencial!</h2>

            <p>
                O universo dos games é incrível! Ele conecta, desafia e diverte. Mas, para que a diversão não vire dor
                de cabeça, é vital saber se proteger. Este guia é para você, adolescente, e para você, pai ou
                responsável, aproveitarem os jogos online de forma segura e consciente. Vamos nessa?
            </p>

            <h2>2. Para Você, Adolescente: Seja um Craque da Segurança!</h2>
            <p>
                Jogar online é demais, mas para uma experiência positiva, tenha atitudes espertas. Lembre-se: <strong>a
                    segurança começa com você!</strong>
            </p>

            <h3>2.1 Boas Práticas no Jogo</h3>
            <ul>
                <li><strong>Pense antes de clicar:</strong> Links estranhos ou ofertas "boas demais" podem ser perigosos. Se
                    desconfiar, não clique!</li>
                <li><strong>Não compartilhe dados pessoais:</strong> Seu nome, endereço, telefone, escola ou fotos não devem
                    ser compartilhados com desconhecidos.</li>
                <li><strong>Use um nickname legal:</strong> Crie um nome de usuário que não revele sua identidade real.</li>
                <li><strong>Cuidado com o que você baixa:</strong> Baixe jogos e atualizações apenas de fontes oficiais para evitar
                    vírus.</li>
            </ul>

            <h3>2.2 Sua Privacidade é um Tesouro</h3>
            <p>As <strong>configurações de privacidade</strong> existem para te proteger. Use-as!</p>
            <ul>
                <li><strong>Configure seu perfil:</strong> Verifique as opções de privacidade do jogo e da plataforma. Deixe-o visível
                    apenas para seus amigos de verdade.</li>
                <li><strong>Cuidado com webcam e microfone:</strong> Pense bem antes de ligar a câmera ou o microfone em
                    jogos com desconhecidos.</li>
            </ul>

            <h3>2.3 Comportamento Respeitoso: Jogue Limpo</h3>
            <p>O ambiente online deve ser de <strong>respeito e diversão</strong>. Seja a pessoa que você gostaria de encontrar
                nos jogos.</p>
            <ul>
                <li><strong>Trate os outros como gostaria de ser tratado:</strong> Evite xingamentos ou cyberbullyng. Se alguém te incomodar, bloqueie e denuncie.</li>
                <li><strong>Não alimente trolls:</strong> Se alguém for tóxico, o melhor é ignorar.</li>
            </ul>

            <h3>2.4 Senhas Fortes e Seguras</h3>
            <p>Sua <strong>senha</strong> é a chave para sua conta. Proteja-a!</p>
            <ul>
                <li><strong>Crie senhas complexas:</strong> Use letras, números e símbolos. Nada de "123456" ou "senha"!</li>
                <li><strong>Senhas diferentes para cada conta:</strong> Assim, se uma for descoberta, as outras estarão seguras. </li>
                <li><strong>Não compartilhe sua senha:</strong> Nem com seu melhor amigo. </li>
                <li><strong>Ative a autenticação de dois fatores (2FA):</strong> Uma camada extra de segurança que pede um
                    código do seu celular. </li>
            </ul>

            <h3>2.5 Fique de Olho nos Golpes!</h3>
            <p>Os golpistas são criativos, mas você pode ser mais esperto!</p>
            <ul>
                <li><strong>Ofertas milagrosas:</strong> Se algo parece bom demais para ser verdade (skins grátis, moedas infinitas),
                    provavelmente é um golpe.</li>
                <li><strong>Phishing:</strong> Mensagens que pedem seus dados de login, fingindo ser da plataforma. Sempre
                    verifique o remetente e o link. </li>
                <li><strong>Contas "emprestadas" ou "vendidas":</strong> Não confie em quem oferece contas de jogos em troca
                    de dinheiro ou dados. </li>
            </ul>

            <h2>3. Para Pais e Responsáveis: Conectando Gerações com Segurança</h2>
            <p>O mundo dos games pode parecer complexo, mas com <strong>informação e diálogo</strong>, vocês podem ser os
                melhores aliados dos seus filhos. A chave é a <strong>participação e a confiança</strong>.</p>

            <h3>3.1 Supervisão e Acompanhamento</h3>
            <ul>
                <li><strong>Conheça os jogos:</strong> Pergunte sobre os jogos, jogue com eles, entenda as classificações etárias. </li>
                <li><strong>Posicione o console/computador em área comum:</strong> Isso facilita a observação e o diálogo. </li>
                <li><strong>Use ferramentas de controle parental:</strong> Explore as configurações para limitar tempo de tela,
                    compras e acesso a conteúdos. </li>
            </ul>

            <h3>3.2. Diálogo Aberto e Sem Julgamento</h3>

            <p>A melhor ferramenta de segurança é a <strong>conversa</strong>.</p>

            <ul>
                <li><strong>Crie um ambiente de confiança:</strong> Seu filho deve saber que pode contar com você em caso de problemas.</li>
                <li><strong>Pergunte sobre as interações:</strong> "Com quem você está jogando?", "O que vocês conversam?". Mostre interesse genuíno.</li>
                <li><strong>Estabeleça regras claras:</strong> Juntos, definam limites de tempo e o que pode ou não ser compartilhado.</li>
            </ul>


            <h3>3.3. Controle de Tempo de Tela e Equilíbrio</h3>

            <p>O <strong>equilíbrio</strong> é fundamental para a saúde e o desenvolvimento.</p>

            <ul>
                <li><strong>Definam horários:</strong> Estabeleçam um tempo máximo diário ou semanal para os jogos.</li>
                <li><strong>Incentive outras atividades:</strong> Garanta tempo para brincar ao ar livre, ler, praticar esportes e interagir offline.</li>
                <li><strong>Evite jogos antes de dormir:</strong> A luz da tela pode atrapalhar o sono.</li>
            </ul>


            <h3>3.4. Compras Dentro do Jogo (Microtransações)</h3>

            <p>Muitos jogos oferecem itens para comprar, o que pode virar um problema sem controle.</p>

            <ul>
                <li><strong>Converse sobre o valor do dinheiro:</strong> Explique que os itens virtuais custam dinheiro real.</li>
                <li><strong>Gerencie as permissões de compra:</strong> Desative a compra com um clique ou exija uma senha.</li>
                <li><strong>Defina um orçamento:</strong> Se permitirem compras, estabeleçam um limite mensal.</li>
            </ul>


            <h3>3.5. Sinais de Risco: Fique Atento!</h3>

            <p>Observe <strong>mudanças no comportamento</strong> que podem indicar que algo não vai bem.</p>

            <ul>
                <li><strong>Mudanças de humor:</strong> Irritabilidade ou tristeza excessiva após jogar.</li>
                <li><strong>Isolamento social:</strong> Preferência por jogar em vez de interagir com a família.</li>
                <li><strong>Queda no desempenho escolar:</strong> Desinteresse pelos estudos.</li>
                <li><strong>Gastos excessivos:</strong> Compras não autorizadas.</li>
                <li><strong>Segredo ou agressividade:</strong> Reações exageradas ao ser questionado sobre o online.</li>
            </ul>

            <p><strong>Atenção:</strong> Se notar vários desses sinais, procure <strong>ajuda profissional</strong> de um psicólogo ou pedagogo. A <strong>saúde mental é prioridade!</strong></p>


            <h2>4. Checklist Rápido de Segurança</h2>

            <p>Um resumo para você e sua família ficarem sempre protegidos:</p>

            <ul class="checklist">
                <li>Senhas fortes e únicas? SIM / NÃO</li>
                <li>Configurações de privacidade ativadas? SIM / NÃO</li>
                <li>Não compartilho dados pessoais? SIM / NÃO</li>
                <li>Trato os outros com respeito? SIM / NÃO</li>
                <li>Converso com meus pais/filhos sobre os jogos? SIM / NÃO</li>
                <li>Limites de tempo de tela definidos? SIM / NÃO</li>
                <li>Compras no jogo controladas? SIM / NÃO</li>
                <li>Sei onde pedir ajuda se precisar? SIM / NÃO</li>
            </ul>


            <h2>5. Como Pedir Ajuda</h2>

            <p>Se algo te incomodar ou te deixar com medo, <strong>não hesite em procurar ajuda</strong>. Você não está sozinho(a)!</p>

            <ul>
                <li><strong>Converse com seus pais ou um adulto de confiança:</strong> Eles estão lá para te apoiar.</li>
                <li><strong>Denuncie dentro do jogo:</strong> A maioria dos jogos tem ferramentas para denunciar comportamentos inadequados.</li>
                <li><strong>Procure canais de ajuda especializados:</strong> Existem organizações que oferecem suporte para casos de cyberbullying e golpes.</li>
            </ul>


            <h2>6. Encerramento: Juntos, a Diversão é Garantida!</h2>

            <p>
                O mundo dos games oferece infinitas possibilidades. Com <strong>informação, diálogo e atitudes conscientes</strong>,
                pais e adolescentes podem ter uma experiência online rica, divertida e, acima de tudo, <strong>segura</strong>.
                A E-Prepag acredita que a diversão é ainda maior quando a segurança é prioridade.
                Joguem juntos, conversem e explorem esse universo incrível com <strong>confiança</strong>!
            </p>


